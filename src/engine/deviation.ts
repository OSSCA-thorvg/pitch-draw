/**
 * 벗어난 정도 — 틀린 음이 펜을 목표선에서 얼마나 밀어내는가.
 *
 * 이 앱의 성공 신호가 걸려 있는 곳이다. **정확히 부르면 변위가 정확히 0 이고, 그래서 펜이
 * 목표선 위를 지난다.** 그림이 제대로 그려진다는 말이 성립하는 이유가 여기 한 줄이다.
 *
 * 전에는 절대 음높이를 화면 세로에 걸었다(음역 → 밴드). 그러면 그릴 수 있는 그림이 곧
 * 부를 수 있는 음역이어서, 세로로 납작한 그림은 1px 에 2옥타브가 얹혔다. 이제는 그림이
 * 어디 있든 상관없이 **목표에서 몇 센트 벗어났는가**만 본다.
 */

import { STAGE_PAD } from '../stage.js';

/**
 * 아무리 틀려도 이만큼까지만 밀려난다(px).
 *
 * 스테이지 여백과 같은 값이다 — 목표선은 여백 안쪽에 맞춰 그려지므로, 여백만큼 밀려나면
 * 정확히 종이 끝에 닿는다. 여백이 있는 이유가 애초에 펜이 선 밖으로 헤맬 자리를 두려는
 * 것이었다.
 */
const MAX_PX = STAGE_PAD;

/**
 * 0 근처에서 얼마나 가파른가(px/센트). 이 값이 판정의 체감을 정한다.
 * 25센트("맞음" 판정폭)에서 약 5px, 반음에서 약 19px 밀려난다.
 */
const PX_PER_CENT = 0.2;

/**
 * 목표 대비 오차. 픽셀이 아니라 센트로 잰다 —
 * 화면 좌표 차이로 재면 그림 크기에 따라 의미가 흔들린다.
 */
export function centsBetween(hz: number, targetHz: number): number {
  return 1200 * Math.log2(hz / targetHz);
}

/**
 * 오차(센트) → 목표선에서 밀려나는 세로 변위(px). 목표선의 y 에 더하면 펜의 y 다.
 *
 * 높게 부르면 위로(음수), 낮게 부르면 아래로 간다. tanh 라 아무리 벗어나도 상한을
 * 넘지 않는다 — 클램프와 달리 끝에 **달라붙지 않아서**, 아주 낮게 부른 구간이 바닥을
 * 따라 기어가는 깔끔한 직선이 되지 않는다. 그건 "재밌게 망함"이 아니라 "기능이 안 됨"
 * 으로 읽힌다.
 */
export function offsetYFromCents(cents: number): number {
  // `+ 0` 은 -0 을 0 으로 만든다. 벗어나지 않았다는 뜻의 값이 둘이면 비교가 지저분해진다.
  return -MAX_PX * Math.tanh((cents * PX_PER_CENT) / MAX_PX) + 0;
}
